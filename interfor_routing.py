#!/usr/bin/env python3
"""
Interfor Dedicated Truck Routing  -  AIMMS-MOPTA 2026 (Option C)
================================================================

Decide, for each of the 1,000 orders, whether it is hauled by one of the dedicated
trucks (and in which multi-stop weekly route) or tendered on the open market, so that
total freight cost is minimised subject to the driver rules.

MODEL (what is actually solved)
-------------------------------
Compact "natural" formulation (arc-based, 3-index) - too big to solve directly for
1,000 orders x 20 trucks, so we apply Dantzig-Wolfe decomposition:

    Route r of truck k  =  ordered list of orders, starting and ending at k's home.
    A route is *feasible* if it satisfies every driver rule on its own:
        * <= 450 mi/day and >= 2 consecutive days off at home  ->  total miles <= 5 x 450 = 2,250
        * deadhead miles <= 50 % of weekly miles                ->  DH <= loaded miles
        * last delivery within 100 mi of the home terminal
        * weekly earnings (sum of lane rates of the loads) >= $4,000

    Master problem (set packing, one per delivery week):
        z[r] in {0,1}   route r is operated
        idle[k] in {0,1} truck k is not used this week
        min  sum_i OpenCost_i  +  sum_r z[r] * ( DHrate*DH_r - sum_{i in r} Surcharge_i )
        s.t. sum_{r ∋ i} z[r] <= 1                 for every order i  (rest goes to open market)
             sum_{r in R_k} z[r] + idle[k] = 1      for every truck k
        (OpenCost_i = lane cost + difficult-lane surcharge; a dedicated truck is paid the plain
         lane cost for each loaded move and DHrate $/mile for empty miles.)

    Routes are generated by column generation: the LP master gives dual prices on orders and
    trucks, and a beam-search pricing heuristic builds new routes with positive reduced profit.
    The final integer master is solved with Gurobi (or HiGHS if Gurobi is not installed).

Usage
-----
    python interfor_routing.py --data "AIMMS-MOPTA Interfor data.xlsx"
    python interfor_routing.py --data data.xlsx --dh-rate 1.0 --fleet 20
"""
from __future__ import annotations

import argparse
import json
import math
import time
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import pandas as pd
import pyomo.environ as pyo

# --------------------------------------------------------------------------------------
# Business rules (from the problem statement)
# --------------------------------------------------------------------------------------
MAX_DAY_MILES = 450          # miles a driver may travel per day
MAX_DRIVING_DAYS = 5         # 7-day week minus 2 consecutive days off at home
MAX_WEEK_MILES = MAX_DAY_MILES * MAX_DRIVING_DAYS
MIN_WEEKLY_EARNINGS = 4000   # $
HOME_RADIUS = 100            # final delivery must be within this many miles of home
MAX_DEADHEAD_SHARE = 0.5     # deadhead <= 50 % of weekly miles

# --------------------------------------------------------------------------------------
# Our own modelling assumptions (not given in the problem; all adjustable from the CLI)
# --------------------------------------------------------------------------------------
DEFAULT_DH_RATE = 1.50       # $/mile Interfor bears for a dedicated truck's empty miles
# Difficult-lane destinations such as "GA_300" are 3-digit ZIP areas, but the data only has
# city names.  Approximate USPS ZIP-3 prefixes for the cities in the data that fall in them:
ZIP3 = {
    "GA_300": ["MARIETTA,GA", "NORCROSS,GA", "SUWANEE,GA", "CUMMING,GA", "COVINGTON,GA"],
    "GA_301": ["ACWORTH,GA", "KENNESAW,GA", "DOUGLASVILLE,GA", "CARROLLTON,GA",
               "CARTERSVILLE,GA", "ADAIRSVILLE,GA"],
    "GA_302": ["FAIRBURN,GA", "UNION CITY,GA", "NEWNAN,GA", "GRIFFIN,GA",
               "HOGANSVILLE,GA", "BARNESVILLE,GA"],
    "GA_303": ["ATLANTA,GA"],
    "GA_306": ["ATHENS,GA", "WINDER,GA"],
    "GA_307": ["RINGGOLD,GA", "RANGER,GA"],
    "FL_330": ["POMPANO BEACH,FL"],
    "KY_402": ["LOUISVILLE,KY"],
    "TN_379": ["KNOXVILLE,TN"],
}
CITY_TO_ZIP3 = {c: z for z, cs in ZIP3.items() for c in cs}


# --------------------------------------------------------------------------------------
# Data
# --------------------------------------------------------------------------------------
@dataclass
class Data:
    loc: list                    # location names
    lidx: dict                   # name -> index
    coords: np.ndarray           # (n,2) lat, lon
    D: np.ndarray                # lane miles
    C: np.ndarray                # lane cost $
    orders: pd.DataFrame         # order, o, t, miles, base, sur, week, due
    trucks: pd.DataFrame         # name, home, h
    week_start: dict = field(default_factory=dict)


def _norm(s: pd.Series) -> pd.Series:
    return s.astype(str).str.strip().str.upper()


def load_data(path: str) -> Data:
    x = pd.read_excel(path, sheet_name=None)
    lanes = x["Lanes"].iloc[:, :4].copy()
    lanes.columns = ["o", "d", "miles", "cost"]
    lanes["o"], lanes["d"] = _norm(lanes["o"]), _norm(lanes["d"])
    lanes = lanes.drop_duplicates(["o", "d"])

    locs = x["Locations"].copy()
    locs["Location"] = _norm(locs["Location"])
    locs = locs.drop_duplicates("Location")
    names = sorted(set(lanes.o) | set(lanes.d))
    lidx = {n: i for i, n in enumerate(names)}
    n = len(names)

    D = np.full((n, n), np.nan)
    C = np.full((n, n), np.nan)
    D[lanes.o.map(lidx), lanes.d.map(lidx)] = lanes.miles.values
    C[lanes.o.map(lidx), lanes.d.map(lidx)] = lanes.cost.values
    assert not np.isnan(D).any(), "lane matrix incomplete"
    coords = np.zeros((n, 2))
    for _, r in locs.iterrows():
        if r.Location in lidx:
            coords[lidx[r.Location]] = (r.Latitude, r.Longitude)

    # difficult lanes: (origin, state | state_zip3) -> extra $/mile on the open market
    dl = x["Difficult Lanes"].copy()
    dl.columns = ["o", "d", "rate"]
    dl["o"], dl["d"] = _norm(dl["o"]), _norm(dl["d"])
    diff = {(r.o, r.d): float(r.rate) for r in dl.itertuples()}

    s = x["Shipments"].copy()
    s.columns = ["order", "origin", "dest", "due"]
    s["origin"], s["dest"] = _norm(s["origin"]), _norm(s["dest"])
    s["o"], s["t"] = s.origin.map(lidx), s.dest.map(lidx)
    s["miles"] = D[s.o, s.t]
    s["base"] = C[s.o, s.t]
    rate = []
    for r in s.itertuples():
        keys = [r.dest[-2:], CITY_TO_ZIP3.get(r.dest)]
        rate.append(max([diff.get((r.origin, k), 0.0) for k in keys if k] or [0.0]))
    s["sur"] = np.array(rate) * s.miles
    dues = sorted(s.due.unique())
    s["week"] = s.due.map({d: i + 1 for i, d in enumerate(dues)})
    week_start = {i + 1: (pd.Timestamp(d) - pd.Timedelta(days=6)).date().isoformat()
                  for i, d in enumerate(dues)}

    c = x["Carriers"].copy()
    c.columns = ["home", "name"]
    c["home"] = _norm(c["home"])
    c["h"] = c.home.map(lidx)
    return Data(names, lidx, coords, D, C, s.reset_index(drop=True), c, week_start)


# --------------------------------------------------------------------------------------
# Routes
# --------------------------------------------------------------------------------------
def route_stats(seq, home, W, D, dh_rate):
    """Miles / earnings / savings of a route (seq = indices into week arrays)."""
    cur, loaded, dh, earn, sur = home, 0.0, 0.0, 0.0, 0.0
    for i in seq:
        dh += D[cur, W["o"][i]]
        loaded += W["miles"][i]
        earn += W["base"][i]
        sur += W["sur"][i]
        cur = W["t"][i]
    dh += D[cur, home]
    return dict(loaded=loaded, dh=dh, miles=loaded + dh, earn=earn, sur=sur,
                saving=sur - dh_rate * dh, last_to_home=D[cur, home])


def is_feasible(st):
    return (st["miles"] <= MAX_WEEK_MILES + 1e-6
            and st["dh"] <= MAX_DEADHEAD_SHARE * st["miles"] + 1e-6
            and st["last_to_home"] <= HOME_RADIUS + 1e-6
            and st["earn"] >= MIN_WEEKLY_EARNINGS - 1e-6)


def beam_price(W, D, home, w, dh_rate, rng, beam=400, m_best=40, m_close=40,
               alpha=0.0, noise=0.0, max_depth=9):
    """Heuristic pricing: build routes for one truck maximising  sum(w_i) - dh_rate*DH.
    Returns a list of feasible order sequences found along the way."""
    n = len(W["o"])
    O, T, Lm, B = W["o"], W["t"], W["miles"], W["base"]
    ret_all = D[T, home]                                     # last stop -> home
    states = [(0.0, home, 0.0, 0.0, 0.0, ())]               # score, cur, miles, deadhead, earn, seq
    found = []
    for _ in range(max_depth):
        nxt = {}
        for score, cur, miles, dh, earn, seq in states:
            dh_leg = D[cur, O]
            mnew = miles + dh_leg + Lm
            ok = mnew + ret_all <= MAX_WEEK_MILES
            if seq:
                ok[list(seq)] = False
            if not ok.any():
                continue
            gain = w - dh_rate * dh_leg + alpha * B
            if noise:
                gain = gain + rng.normal(0, noise, n)
            cand = np.where(ok)[0]
            pick = set(cand[np.argsort(-gain[cand])[:m_best]])
            cl = cand[ret_all[cand] <= HOME_RADIUS]
            if len(cl):
                pick |= set(cl[np.argsort(-gain[cl])[:m_close]])
            for j in pick:
                s2 = score + gain[j]
                seq2 = seq + (int(j),)
                key = (frozenset(seq2), int(T[j]))
                if key not in nxt or nxt[key][0] < s2:
                    nxt[key] = (s2, int(T[j]), mnew[j], dh + dh_leg[j], earn + B[j], seq2)
        if not nxt:
            break
        states = sorted(nxt.values(), key=lambda s: -s[0])[:beam]
        for _, cur, miles, dh, earn, seq in states:
            ret = D[cur, home]
            if (ret <= HOME_RADIUS and earn >= MIN_WEEKLY_EARNINGS
                    and miles + ret <= MAX_WEEK_MILES and dh + ret <= miles - dh + 1e-6):
                found.append(seq)
    return found


# --------------------------------------------------------------------------------------
# Pyomo master problem
# --------------------------------------------------------------------------------------
def pick_solver(prefer=("gurobi", "appsi_highs", "scip", "cbc")):
    for name in prefer:
        try:
            if pyo.SolverFactory(name).available(exception_flag=False):
                return name
        except Exception:
            pass
    raise RuntimeError("no MILP solver found (install gurobipy or highspy)")


def build_master(K, pool, order_ids, base_cost_constant, dh_rate, allow_idle,
                 max_active=None, integer=True, idle_penalty=1e5):
    """pool: list of dicts(k, seq, saving, ...).  Minimise total cost - constant."""
    m = pyo.ConcreteModel("Interfor_weekly_master")
    m.K = pyo.Set(initialize=K)
    m.R = pyo.RangeSet(0, len(pool) - 1)
    m.I = pyo.Set(initialize=order_ids)
    dom = pyo.Binary if integer else pyo.NonNegativeReals
    m.z = pyo.Var(m.R, domain=dom)
    m.idle = pyo.Var(m.K, domain=dom)

    cover = {i: [] for i in order_ids}
    by_truck = {k: [] for k in K}
    for r, col in enumerate(pool):
        by_truck[col["k"]].append(r)
        for i in col["seq"]:
            cover[i].append(r)

    # objective: change in cost relative to sending everything to the open market
    m.Obj = pyo.Objective(
        expr=sum(-pool[r]["saving"] * m.z[r] for r in m.R)
        + (0 if allow_idle else idle_penalty) * sum(m.idle[k] for k in K),
        sense=pyo.minimize)
    m.Cover = pyo.Constraint(m.I, rule=lambda m, i: sum(m.z[r] for r in cover[i]) <= 1
                             if cover[i] else pyo.Constraint.Skip)
    m.Truck = pyo.Constraint(m.K, rule=lambda m, k: sum(m.z[r] for r in by_truck[k]) + m.idle[k] == 1)
    if max_active is not None:
        m.Fleet = pyo.Constraint(expr=sum(m.idle[k] for k in K) >= len(K) - max_active)
    if not integer:
        m.dual = pyo.Suffix(direction=pyo.Suffix.IMPORT)
    return m


def lp_duals(m, solver_name):
    opt = pyo.SolverFactory(solver_name)
    opt.solve(m)
    y_i = {i: m.dual.get(m.Cover[i], 0.0) for i in m.I if (i in m.Cover)}
    y_k = {k: m.dual.get(m.Truck[k], 0.0) for k in m.K}
    return pyo.value(m.Obj), y_i, y_k


# --------------------------------------------------------------------------------------
# Weekly solve (column generation + integer master)
# --------------------------------------------------------------------------------------
def solve_week(data: Data, week: int, dh_rate, fleet, allow_idle, seed=0, verbose=True,
               max_iter=18, time_limit=120, active_levels=()):
    rng = np.random.default_rng(seed + week)
    od = data.orders[data.orders.week == week].reset_index(drop=True)
    W = dict(o=od.o.values, t=od.t.values, miles=od.miles.values, base=od.base.values,
             sur=od.sur.values, ids=od.order.values)
    trucks = data.trucks.iloc[:fleet].reset_index(drop=True)
    K = list(range(len(trucks)))
    n = len(od)
    open_total = float((od.base + od.sur).sum())
    solver = pick_solver()
    lp_solver = pick_solver(("gurobi", "appsi_highs"))
    pool, seen = [], set()

    def add_routes(k, seqs):
        added = 0
        for seq in seqs:
            key = (k, seq)
            if key in seen:
                continue
            st = route_stats(seq, trucks.h[k], W, data.D, dh_rate)
            if is_feasible(st):
                seen.add(key)
                pool.append(dict(k=k, seq=seq, **st))
                added += 1
        return added

    variants = [(0.0, 0.0), (0.15, 0.0), (0.4, 0.0), (0.0, 60.0), (0.15, 90.0), (0.4, 120.0)]
    t0 = time.time()
    # --- initial columns: price with raw surcharges (duals = 0) ---
    w0 = W["sur"].copy()
    for k in K:
        for a, nz in variants:
            add_routes(k, beam_price(W, data.D, trucks.h[k], w0, dh_rate, rng, alpha=a, noise=nz))
    if verbose:
        print(f"  week {week}: {n} orders, {len(K)} trucks, initial pool {len(pool)} routes "
              f"({time.time() - t0:.0f}s)")

    lp_obj = None
    for it in range(max_iter):
        m = build_master(K, pool, list(range(n)), open_total, dh_rate, allow_idle, integer=False)
        lp_obj, y_i, y_k = lp_duals(m, lp_solver)
        w = W["sur"] + np.array([y_i.get(i, 0.0) for i in range(n)])      # y_i <= 0
        new = 0
        for k in K:
            best = []
            for a, nz in variants[: 3 if it > 2 else 6]:
                best += beam_price(W, data.D, trucks.h[k], w, dh_rate, rng, alpha=a, noise=nz)
            # keep only columns with positive reduced profit  (value + y_k > eps)
            scored = []
            for seq in set(best):
                if (k, seq) in seen:
                    continue
                st = route_stats(seq, trucks.h[k], W, data.D, dh_rate)
                val = sum(w[i] for i in seq) - dh_rate * st["dh"] + y_k[k]
                if val > 1e-3 and is_feasible(st):
                    scored.append((val, seq))
            scored.sort(reverse=True)
            new += add_routes(k, [s for _, s in scored[:25]])
        if verbose:
            print(f"    CG iter {it + 1:2d}: LP saving {-lp_obj:10.2f}   pool {len(pool):5d}   +{new}")
        if new == 0:
            break

    def solve_int(max_active=None):
        mi = build_master(K, pool, list(range(n)), open_total, dh_rate, allow_idle,
                          max_active=max_active, integer=True)
        opt = pyo.SolverFactory(solver)
        if solver == "gurobi":
            opt.options['TimeLimit'] = time_limit
            opt.options['MIPGap'] = 1e-4
        elif solver == "appsi_highs":
            opt.options["time_limit"] = float(time_limit)
            opt.options["mip_rel_gap"] = 1e-4
        res = opt.solve(mi, load_solutions=True)
        return mi, res

    mi, res = solve_int()
    chosen = [r for r in mi.R if pyo.value(mi.z[r]) > 0.5]
    idle = [k for k in K if pyo.value(mi.idle[k]) > 0.5]
    saving = -pyo.value(mi.Obj) - (0 if allow_idle else 1e5 * len(idle))
    out = dict(week=week, open_total=open_total, saving=saving, lp_saving=-lp_obj,
               chosen=[pool[r] for r in chosen], idle=idle, pool=len(pool),
               solver=solver, runtime=time.time() - t0, W=W, trucks=trucks)
    # fleet-size sensitivity from the same column pool (best N trucks may work, rest idle)
    sens = {}
    for N in active_levels:
        mi2, _ = solve_int(max_active=N)
        sens[N] = -pyo.value(mi2.Obj)
    out["sens"] = sens
    return out


# --------------------------------------------------------------------------------------
# Turn routes into a day-by-day plan and validate it independently
# --------------------------------------------------------------------------------------
def build_plan(data: Data, res, dh_rate):
    W, trucks = res["W"], res["trucks"]
    D, names = data.D, data.loc
    start = pd.Timestamp(data.week_start[res["week"]])
    plan = []
    for col in res["chosen"]:
        k, home = col["k"], int(trucks.h[col["k"]])
        legs, cur = [], home
        for i in col["seq"]:
            if D[cur, W["o"][i]] > 0:
                legs.append(("deadhead", cur, int(W["o"][i]), D[cur, W["o"][i]], None))
            legs.append(("loaded", int(W["o"][i]), int(W["t"][i]), W["miles"][i], int(W["ids"][i])))
            cur = int(W["t"][i])
        if D[cur, home] > 0:
            legs.append(("deadhead", cur, home, D[cur, home], None))
        cum, out_legs, total_by_day = 0.0, [], {}
        for kind, a, b, mi, oid in legs:
            s, e = cum, cum + mi
            d0 = int(s // MAX_DAY_MILES) + 1
            d1 = max(d0, int(math.ceil(e / MAX_DAY_MILES - 1e-9)))
            for d in range(d0, d1 + 1):
                lo, hi = max(s, (d - 1) * MAX_DAY_MILES), min(e, d * MAX_DAY_MILES)
                total_by_day[d] = total_by_day.get(d, 0) + max(0.0, hi - lo)
            out_legs.append(dict(kind=kind, frm=names[a], to=names[b], miles=round(float(mi), 1),
                                 order=oid, day_start=d0, day_end=d1,
                                 date_end=(start + pd.Timedelta(days=d1 - 1)).date().isoformat()))
            cum = e
        plan.append(dict(
            week=res["week"], truck=trucks.name[k], home=names[home], legs=out_legs,
            orders=[int(W["ids"][i]) for i in col["seq"]],
            loaded=round(col["loaded"], 1), deadhead=round(col["dh"], 1),
            miles=round(col["miles"], 1), dh_share=round(col["dh"] / col["miles"], 3),
            earnings=round(col["earn"], 2), surcharge_avoided=round(col["sur"], 2),
            dh_cost=round(dh_rate * col["dh"], 2), saving=round(col["saving"], 2),
            days_driving=max(total_by_day) if total_by_day else 0,
            day_miles={d: round(v, 1) for d, v in sorted(total_by_day.items())},
            last_stop_to_home=round(col["last_to_home"], 1)))
    return plan


def validate(plan, tag=""):
    """Re-check every driver rule on the final plan (independent of the optimiser)."""
    bad = []
    for p in plan:
        if p["earnings"] < MIN_WEEKLY_EARNINGS - 1e-6: bad.append((p["truck"], "earnings"))
        if p["last_stop_to_home"] > HOME_RADIUS + 1e-6: bad.append((p["truck"], "home radius"))
        if p["dh_share"] > MAX_DEADHEAD_SHARE + 1e-6: bad.append((p["truck"], "deadhead"))
        if max(p["day_miles"].values(), default=0) > MAX_DAY_MILES + 1e-6: bad.append((p["truck"], "daily miles"))
        if p["days_driving"] > MAX_DRIVING_DAYS: bad.append((p["truck"], "2 days off"))
    seen = [o for p in plan for o in p["orders"]]
    if len(seen) != len(set(seen)): bad.append(("-", "order served twice"))
    return bad


# --------------------------------------------------------------------------------------
# Driver
# --------------------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", required=True)
    ap.add_argument("--out", default="results")
    ap.add_argument("--fleet", type=int, default=20, help="number of dedicated trucks (<= 20 in data)")
    ap.add_argument("--dh-rate", type=float, default=DEFAULT_DH_RATE, help="$/mile cost of empty miles")
    ap.add_argument("--require-all-trucks", action="store_true",
                    help="force every truck to run a compliant route (default: a truck with no compliant/"
                         "worthwhile route stays idle - e.g. homes with no delivery lane within 100 mi)")
    ap.add_argument("--time-limit", type=int, default=120)
    ap.add_argument("--sens", default="0,5,10,15,20", help="fleet sizes for the sensitivity curve")
    a = ap.parse_args()

    data = load_data(a.data)
    out = Path(a.out); out.mkdir(exist_ok=True, parents=True)
    levels = [int(v) for v in a.sens.split(",") if v != ""]
    print(f"{len(data.orders)} orders | {int((data.orders.sur > 0).sum())} on difficult lanes "
          f"(surcharge ${data.orders.sur.sum():,.0f}) | {len(data.trucks)} carriers")

    weeks, plans, all_bad = [], [], []
    for wk in sorted(data.orders.week.unique()):
        res = solve_week(data, wk, a.dh_rate, a.fleet, not a.require_all_trucks, time_limit=a.time_limit,
                         active_levels=[n for n in levels if 0 < n < a.fleet])
        plan = build_plan(data, res, a.dh_rate)
        all_bad += validate(plan)
        plans += plan
        weeks.append(res)
        print(f"  week {wk}: saving ${res['saving']:,.0f} vs all-open-market "
              f"| {len(plan)} routes, {sum(len(p['orders']) for p in plan)} orders dedicated, "
              f"idle trucks {len(res['idle'])} | solver {res['solver']} {res['runtime']:.0f}s")

    open_total = sum(r["open_total"] for r in weeks)
    saving = sum(r["saving"] for r in weeks)
    ded_orders = sum(len(p["orders"]) for p in plans)
    sens = {0: 0.0}
    for N in levels:
        if N == a.fleet:
            sens[N] = saving
        elif N > 0:
            sens[N] = sum(r["sens"].get(N, 0.0) for r in weeks)
    summary = dict(
        orders=len(data.orders), dedicated_orders=ded_orders, open_market_orders=len(data.orders) - ded_orders,
        cost_all_open_market=round(open_total, 2), total_cost=round(open_total - saving, 2),
        saving=round(saving, 2), saving_pct=round(100 * saving / open_total, 2),
        surcharge_avoided=round(sum(p["surcharge_avoided"] for p in plans), 2),
        deadhead_cost=round(sum(p["dh_cost"] for p in plans), 2),
        avg_dh_share=round(float(np.mean([p["dh_share"] for p in plans])), 3) if plans else 0,
        avg_weekly_earnings=round(float(np.mean([p["earnings"] for p in plans])), 2) if plans else 0,
        idle_truck_weeks=sum(len(r["idle"]) for r in weeks),
        dh_rate=a.dh_rate, fleet=a.fleet, violations=all_bad,
        sensitivity={str(k): round(v, 2) for k, v in sorted(sens.items())})
    print(json.dumps(summary, indent=2))

    (out / "summary.json").write_text(json.dumps(summary, indent=2))
